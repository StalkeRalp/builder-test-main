// ====== CURRENT LANGUAGE STATE ======
// Default is 'fr' as requested by user
let currentLang = localStorage.getItem('tde_lang') || 'fr';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (lang !== 'fr' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('tde_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations(lang);
  updateLanguageUI();
}

export function applyTranslations(lang = currentLang) {
  const dict = translations[lang] || translations.fr;
  
  // Find all elements with data-i18n attribute
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // Check if element has child HTML elements or if simple text
      if (el.children.length === 0 || el.hasAttribute('data-i18n-html')) {
        el.innerHTML = dict[key];
      } else {
        // If element contains icons/spans, attempt text node replacement or innerHTML fallback
        const textNode = Array.from(el.childNodes).find(node => node.nodeType === Node.TEXT_NODE);
        if (textNode) {
          textNode.textContent = dict[key];
        } else {
          el.innerHTML = dict[key];
        }
      }
    }
  });

  // Handle elements with data-i18n-placeholder
  const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });
}

function updateLanguageUI() {
  const langBtns = document.querySelectorAll('.lang-btn');
  langBtns.forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === currentLang) {
      btn.classList.add('bg-blue-600', 'text-white', 'border-blue-400/40', 'shadow-md');
      btn.classList.remove('text-slate-400', 'hover:text-white', 'hover:bg-white/10');
    } else {
      btn.classList.remove('bg-blue-600', 'text-white', 'border-blue-400/40', 'shadow-md');
      btn.classList.add('text-slate-400', 'hover:text-white', 'hover:bg-white/10');
    }
  });
}

export function initI18n() {
  document.documentElement.lang = currentLang;
  applyTranslations(currentLang);
  updateLanguageUI();

  // Attach event listener to language switch buttons
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) {
      const targetLang = btn.getAttribute('data-lang');
      if (targetLang) {
        setLanguage(targetLang);
      }
    }
  });
}
